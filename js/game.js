// ─── セッション管理（トップレベルフローの多重実行防止） ────────────
// startGame / startAreaPlay / debugJumpXxx など「新しい進行を開始する」処理は
// 必ず _beginSession() でトークンを更新してから進む。for ループや await の後で
// _isCurrentSession(mySession) を確認し、不一致なら即座に処理を打ち切ることで、
// 例えばデバッグパネルで別ステージへジャンプした際に「古いステージの進行ループ」が
// scores / currentArea など共有状態を裏で書き換え続けてしまう競合を防ぐ。
let _sessionToken = 0;

function _isCurrentSession(token) {
  return token === _sessionToken;
}

/** 実行中の古いフローを無効化する（トークンのみ更新。_gameAborted には触れない）。 */
function _invalidateSession() {
  // エフェクト確認画面のループがバックグラウンドで動き続けるのを防ぐ
  // （右上のデバッグパネルはどの画面からも操作できるため、エフェクト確認画面から
  //   離れた後もループと keydown リスナーが残り続けると別画面で誤動作する）。
  if (_fxDebugActive) {
    _fxDebugActive = false;
    _fxDebugPose   = null;
    window.removeEventListener('keydown', _fxDebugOnKey);
  }

  // チュートリアルの吹き出しが表示されたままなら閉じる。
  // #tutorial-overlay は screen-* の外にあるため showScreen() だけでは隠れず、
  // 表示中にデバッグジャンプすると新しい画面の上に古い吹き出しが残ってしまう。
  const tutOverlay = document.getElementById('tutorial-overlay');
  if (tutOverlay && tutOverlay.style.display !== 'none') {
    tutOverlay.style.display = 'none';
    const canvasArt       = document.getElementById('canvas-art');
    const titleCharacter  = document.querySelector('.title-character');
    if (canvasArt) canvasArt.style.display = 'none';
    if (titleCharacter) titleCharacter.style.display = 'none';
    if (window.TutorialModule?.TutorialCharacter) window.TutorialModule.TutorialCharacter.hide();
  }

  return ++_sessionToken;
}

/** 新しいトップレベルフロー（スタート/エリア開始/デバッグジャンプ等）を開始する。 */
function _beginSession() {
  _invalidateSession();
  _gameAborted = false;
  return _sessionToken;
}

