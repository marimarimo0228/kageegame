function _renderPositionEditor() {
  const ground = document.getElementById('poseditor-map-image');
  if (!ground || !_posEditAreas) return;

  ground.querySelectorAll('.poseditor-box').forEach((el) => el.remove());
  for (const area of _posEditAreas) {
    const box = document.createElement('div');
    box.className     = 'poseditor-box';
    box.dataset.areaId = area.id;
    box.style.left = `${area.x}%`;
    box.style.top  = `${area.y}%`;

    const label = document.createElement('div');
    label.className   = 'poseditor-label';
    label.textContent = area.label;
    box.appendChild(label);

    const coord = document.createElement('div');
    coord.className   = 'poseditor-coord';
    coord.textContent = `${area.x.toFixed(1)}, ${area.y.toFixed(1)}`;
    box.appendChild(coord);

    _bindPositionEditorDrag(box, ground, area);
    ground.appendChild(box);
  }
}

function _bindPositionEditorDrag(box, ground, area) {
  let dragging = false;

  const onMove = (e) => {
    if (!dragging) return;
    e.preventDefault();
    const rect = ground.getBoundingClientRect();
    const src  = e.touches ? e.touches[0] : e;
    let x = ((src.clientX - rect.left) / rect.width)  * 100;
    let y = ((src.clientY - rect.top)  / rect.height) * 100;
    x = Math.max(0, Math.min(100, x));
    y = Math.max(0, Math.min(100, y));
    area.x = Math.round(x * 10) / 10;
    area.y = Math.round(y * 10) / 10;
    box.style.left = `${area.x}%`;
    box.style.top  = `${area.y}%`;
    const coordEl = box.querySelector('.poseditor-coord');
    if (coordEl) coordEl.textContent = `${area.x.toFixed(1)}, ${area.y.toFixed(1)}`;
  };
  const onUp = () => {
    dragging = false;
    window.removeEventListener('mousemove', onMove);
    window.removeEventListener('mouseup',   onUp);
    window.removeEventListener('touchmove', onMove);
    window.removeEventListener('touchend',  onUp);
  };
  const onDown = (e) => {
    e.preventDefault();
    dragging = true;
    window.addEventListener('mousemove', onMove, { passive: false });
    window.addEventListener('mouseup',   onUp);
    window.addEventListener('touchmove', onMove, { passive: false });
    window.addEventListener('touchend',  onUp);
  };

  box.addEventListener('mousedown',  onDown);
  box.addEventListener('touchstart', onDown, { passive: false });
}

/** 現在の座標一覧をJSONとして出力欄に表示し、クリップボードへコピーを試みる */
function posEditorOutput() {
  const outEl = document.getElementById('poseditor-output');
  if (!outEl || !_posEditAreas) return;

  const json = JSON.stringify(
    _posEditAreas.map(({ id, x, y }) => ({ id, x, y })),
    null, 2
  );
  outEl.style.display = 'block';
  outEl.value = json;
  outEl.focus();
  outEl.select();

  const statusEl = document.getElementById('poseditor-status');
  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(json)
      .then(() => { if (statusEl) statusEl.textContent = '座標をコピーしました。この内容をClaude Codeに伝えてください。'; })
      .catch(() => { if (statusEl) statusEl.textContent = '座標を表示しました。下の内容をコピーしてClaude Codeに伝えてください。'; });
  } else if (statusEl) {
    statusEl.textContent = '座標を表示しました。下の内容をコピーしてClaude Codeに伝えてください。';
  }
}

